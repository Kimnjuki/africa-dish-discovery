/**
 * Sync curated client substitution edges into public.ingredient_substitutions.
 * Resolves names via ingredients + aliases; writes SQL for supabase db query.
 *
 * Usage: node scripts/sync-substitutions-from-graph.mjs
 */

import { writeFileSync, mkdirSync, readFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

function loadEnv() {
  const envPath = resolve(root, ".env");
  if (!existsSync(envPath)) return {};
  return Object.fromEntries(
    readFileSync(envPath, "utf8")
      .split(/\r?\n/)
      .filter((l) => l && !l.startsWith("#") && l.includes("="))
      .map((l) => {
        const i = l.indexOf("=");
        return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^["']|["']$/g, "")];
      })
  );
}

const env = { ...loadEnv(), ...process.env };
const SUPABASE_URL = env.SUPABASE_URL || env.VITE_SUPABASE_URL;
const KEY = env.VITE_SUPABASE_PUBLISHABLE_KEY || env.SUPABASE_PUBLISHABLE_KEY;

function normalize(s) {
  return String(s || "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

async function fetchAll(path) {
  const headers = { apikey: KEY, Authorization: `Bearer ${KEY}`, Prefer: "count=exact" };
  const out = [];
  let from = 0;
  for (;;) {
    const res = await fetch(`${SUPABASE_URL}/rest/v1/${path}`, {
      headers: { ...headers, Range: `${from}-${from + 999}` },
    });
    if (!res.ok) throw new Error(await res.text());
    const batch = await res.json();
    out.push(...batch);
    if (batch.length < 1000) break;
    from += 1000;
  }
  return out;
}

// Parse SUBSTITUTION_EDGE_DEFS from source (lightweight regex extract of from/to pairs)
function parseEdgesFromSource() {
  const src = readFileSync(resolve(root, "src/lib/substitutionGraph.ts"), "utf8");
  const edges = [];
  const re =
    /from:\s*"([^"]+)"[\s\S]*?to:\s*"([^"]+)"[\s\S]*?(?:compatibilityScore:\s*(\d+))?[\s\S]*?(?:bidirectional:\s*true)?/g;
  // More reliable: split on objects starting with from:
  const blocks = src.split(/\n\s*\{\s*\n\s*from:/).slice(1);
  for (const block of blocks) {
    const fromM = block.match(/^\s*"([^"]+)"/) || block.match(/from:\s*"([^"]+)"/);
    const toM = block.match(/to:\s*"([^"]+)"/);
    const scoreM = block.match(/compatibilityScore:\s*(\d+)/);
    const reasonM = block.match(/reason:\s*"([^"]+)"/);
    const notesM = block.match(/notes:\s*"([^"]+)"/);
    const bi = /bidirectional:\s*true/.test(block);
    const ratioM = block.match(/ratio:\s*([\d.]+)/);
    if (!fromM || !toM) continue;
    const from = fromM[1];
    const to = toM[1];
    const edge = {
      from,
      to,
      score: scoreM ? Number(scoreM[1]) : 70,
      reason: reasonM ? reasonM[1] : "Curated graph edge",
      notes: notesM ? notesM[1] : "",
      ratio: ratioM ? Number(ratioM[1]) : 1,
    };
    edges.push(edge);
    if (bi) edges.push({ ...edge, from: to, to: from });
  }
  return edges;
}

function sqlLit(s) {
  if (s == null) return "NULL";
  return `'${String(s).replace(/'/g, "''")}'`;
}

async function main() {
  const edges = parseEdgesFromSource();
  console.log(`Parsed ${edges.length} directed edges from substitutionGraph.ts`);

  const [ingredients, aliases] = await Promise.all([
    fetchAll("ingredients?select=id,name,slug,canonical_name"),
    fetchAll("ingredient_aliases?select=ingredient_id,alias,alias_normalized"),
  ]);

  const lookup = new Map();
  for (const ing of ingredients) {
    for (const k of [ing.name, ing.canonical_name, ing.slug]) {
      const n = normalize(k);
      if (n && !lookup.has(n)) lookup.set(n, ing.id);
    }
  }
  for (const a of aliases) {
    const n = normalize(a.alias_normalized || a.alias);
    if (n && !lookup.has(n)) lookup.set(n, a.ingredient_id);
  }

  const resolved = [];
  const unresolved = [];
  for (const e of edges) {
    const oid = lookup.get(normalize(e.from));
    const sid = lookup.get(normalize(e.to));
    if (!oid || !sid) {
      unresolved.push(e);
      continue;
    }
    if (oid === sid) continue;
    resolved.push({ ...e, oid, sid });
  }

  console.log(`Resolved ${resolved.length}; unresolved ${unresolved.length}`);
  if (unresolved.length) {
    console.log(
      "  sample unresolved:",
      unresolved.slice(0, 12).map((u) => `${u.from}→${u.to}`).join(", ")
    );
  }

  const lines = [
    "-- Generated by scripts/sync-substitutions-from-graph.mjs",
    "BEGIN;",
  ];
  for (const e of resolved) {
    lines.push(`INSERT INTO public.ingredient_substitutions (
  original_ingredient_id, substitute_ingredient_id, quantity_ratio, compatibility_score,
  reason, notes, substitution_type, confidence, is_verified, review_status, source
) SELECT ${sqlLit(e.oid)}::uuid, ${sqlLit(e.sid)}::uuid, ${e.ratio}, ${e.score},
  ${sqlLit(e.reason)}, ${sqlLit(e.notes)}, 'functional', ${e.score / 100}, true, 'approved', 'client-graph-sync-v1'
WHERE NOT EXISTS (
  SELECT 1 FROM public.ingredient_substitutions x
  WHERE x.original_ingredient_id = ${sqlLit(e.oid)}::uuid
    AND x.substitute_ingredient_id = ${sqlLit(e.sid)}::uuid
);`);
  }
  lines.push("COMMIT;");

  mkdirSync(resolve(root, "output"), { recursive: true });
  const sqlPath = resolve(root, "output/sync_substitutions_from_graph.sql");
  writeFileSync(sqlPath, lines.join("\n") + "\n");
  writeFileSync(
    resolve(root, "output/sync_substitutions_report.json"),
    JSON.stringify(
      { generated_at: new Date().toISOString(), parsed: edges.length, resolved: resolved.length, unresolved },
      null,
      2
    )
  );
  console.log(`Wrote ${sqlPath}`);
  console.log("Apply with: npx supabase db query --remote --yes -f output/sync_substitutions_from_graph.sql");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
